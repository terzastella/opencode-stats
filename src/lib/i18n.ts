/** System language -> app language (Italian default, English otherwise). */
export function detectLang(): Lang {
  try {
    const nav = typeof navigator !== "undefined" ? navigator.language : "";
    return nav.toLowerCase().startsWith("en") ? "en" : "it";
  } catch {
    return "it";
  }
}
